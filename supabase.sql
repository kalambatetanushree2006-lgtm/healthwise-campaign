-- HealthWise campaign database setup for Supabase
-- Run this script in Supabase > SQL Editor.
-- This intentionally stores anonymous quiz scores and consented feedback only.
-- Do NOT add a service_role key to your website.

create table if not exists public.quiz_responses (
  id bigint generated by default as identity primary key,
  score integer not null check (score >= 0 and score <= 5),
  total integer not null default 5 check (total = 5),
  created_at timestamptz not null default now()
);

create table if not exists public.feedback_responses (
  id bigint generated by default as identity primary key,
  display_name text,
  rating integer not null check (rating >= 1 and rating <= 5),
  useful_topic text not null,
  comment text,
  consent boolean not null default false,
  created_at timestamptz not null default now(),
  constraint comment_length check (comment is null or char_length(comment) <= 500),
  constraint name_length check (display_name is null or char_length(display_name) <= 60)
);

alter table public.quiz_responses enable row level security;
alter table public.feedback_responses enable row level security;

-- Visitors may submit a quiz result and read aggregate source rows for the dashboard.
-- For a public student project, these policies make the dashboard transparent.
-- They do not allow visitors to update or delete submissions.
drop policy if exists "Public can submit quiz scores" on public.quiz_responses;
create policy "Public can submit quiz scores"
on public.quiz_responses for insert to anon
with check (score between 0 and 5 and total = 5);

drop policy if exists "Public can read quiz counts and scores" on public.quiz_responses;
create policy "Public can read quiz counts and scores"
on public.quiz_responses for select to anon
using (true);

drop policy if exists "Public can submit feedback" on public.feedback_responses;
create policy "Public can submit feedback"
on public.feedback_responses for insert to anon
with check (
  rating between 1 and 5
  and consent = true
  and char_length(useful_topic) <= 100
  and (comment is null or char_length(comment) <= 500)
  and (display_name is null or char_length(display_name) <= 60)
);

drop policy if exists "Public can read consented feedback" on public.feedback_responses;
create policy "Public can read consented feedback"
on public.feedback_responses for select to anon
using (consent = true);

